function generateContracts(id: TemplateId, cfg: Record<string, string>, ver: string): GenFile[] {
  switch (id) {
    case "erc20-token":       return erc20Contracts(cfg, ver);
    case "nft-collection":    return nftContracts(cfg, ver);
    case "dao-governance":    return daoContracts(cfg, ver);
    case "staking-dashboard": return stakingContracts(cfg, ver);
    case "meme-token":        return memeContracts(cfg, ver);
    default:                  return [];
  }
}

