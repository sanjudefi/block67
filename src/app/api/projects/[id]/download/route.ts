// ── ZIP builder ───────────────────────────────────────────────────────────────

async function buildZip(files: GenFile[], rootDir: string): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const archive = archiver("zip", { zlib: { level: 9 } });
    const chunks:  Buffer[] = [];

    archive.on("data",  (chunk: Buffer) => chunks.push(chunk));
    archive.on("end",   () => resolve(Buffer.concat(chunks)));
    archive.on("error", reject);

    for (const file of files) {
      archive.append(file.content, { name: `${rootDir}/${file.path}` });
    }

    archive.finalize();
  });
}

// ── Route handler ─────────────────────────────────────────────────────────────

export async function POST(req: NextRequest, { params }: { params: { id: string } }) {
  const session = await getServerSession(authOptions);
  if (!session?.user?.id) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const project = await prisma.project.findFirst({
    where: { id: params.id, ownerId: session.user.id },
  });
  if (!project) {
    return NextResponse.json({ error: "Not found" }, { status: 404 });
  }

  const opts: DownloadOptions = await req.json();
  const cfg        = project.paramValues as Record<string, string>;
  const templateId = (cfg._templateKey ?? "erc20-token") as TemplateId;
  const rootDir    = opts.projectName.toLowerCase().replace(/[^a-z0-9-]/g, "-");
  const solVer     = opts.solidityVersion ?? "0.8.20";

  // Gather all files
  const contractFiles = generateContracts(templateId, cfg, solVer)
    .map((f) => ({
      ...f,
      // Foundry uses src/ instead of contracts/
      path: opts.framework === "foundry"
        ? f.path.replace("contracts/", "src/")
        : f.path,
    }));

  const configFiles = opts.framework === "hardhat"
    ? hardhatConfig(opts)
    : opts.framework === "foundry"
      ? foundryConfig(opts)
      : truffleConfig(opts);

  const allFiles: GenFile[] = [
    ...contractFiles,
    ...configFiles,
    deployScript(templateId, cfg, opts.framework),
    ...(opts.includeTests ? [testFile(templateId, cfg, opts.framework)] : []),
    block67Config(templateId, cfg, opts),
    envExample(opts),
    readme(templateId, cfg, opts),
    { path: ".gitignore", content: `node_modules/\n.env\nartifacts/\ncache/\nout/\n` },
  ];

  const zipBuffer = await buildZip(allFiles, rootDir);

  return new Response(zipBuffer.buffer as ArrayBuffer, {
    headers: {
      "Content-Type":        "application/zip",
      "Content-Disposition": `attachment; filename="${rootDir}.zip"`,
      "Content-Length":      zipBuffer.length.toString(),
    },
  });
}
