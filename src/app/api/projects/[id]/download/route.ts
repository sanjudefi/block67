// ── Deploy scripts ────────────────────────────────────────────────────────────

function deployScript(
  templateId: TemplateId,
  cfg: Record<string, string>,
  framework: string,
): GenFile {
  const contracts = generateContracts(templateId, cfg, "0.8.20")
    .map((f) => f.path.replace("contracts/", "").replace("src/", "").replace(".sol", ""));

  if (framework === "foundry") {
    return {
      path: "script/Deploy.s.sol",
      content: `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

import "forge-std/Script.sol";
${contracts.map((c) => `import "../src/${c}.sol";`).join("\n")}

contract DeployScript is Script {
    function run() external {
        uint256 deployerPrivateKey = vm.envUint("PRIVATE_KEY");
        address deployer = vm.addr(deployerPrivateKey);

        vm.startBroadcast(deployerPrivateKey);

        console.log("Deploying contracts from:", deployer);

${contracts.map((c, i) => `        ${c} ${c.toLowerCase()} = new ${c}(deployer);\n        console.log("${c} deployed to:", address(${c.toLowerCase()}));`).join("\n\n")}

        vm.stopBroadcast();
    }
}
`,
    };
  }

  if (framework === "truffle") {
    return {
      path: "migrations/1_deploy_contracts.js",
      content: `${contracts.map((c) => `const ${c} = artifacts.require("${c}");`).join("\n")}

module.exports = async function (deployer, network, accounts) {
  const [deployer_addr] = accounts;
  console.log("Deploying from:", deployer_addr, "on", network);

${contracts.map((c) => `  await deployer.deploy(${c}, deployer_addr);\n  const ${c.toLowerCase()} = await ${c}.deployed();\n  console.log("${c}:", ${c.toLowerCase()}.address);`).join("\n\n")}
};
`,
    };
  }

  // Hardhat (default)
  return {
    path: "scripts/deploy.js",
    content: `const { ethers } = require("hardhat");

async function main() {
  const [deployer] = await ethers.getSigners();
  console.log("Deploying contracts with:", deployer.address);
  console.log("Balance:", ethers.formatEther(await ethers.provider.getBalance(deployer.address)), "ETH");

${contracts.map((c) => `  const ${c}Factory = await ethers.getContractFactory("${c}");
  const ${c.toLowerCase()} = await ${c}Factory.deploy(deployer.address);
  await ${c.toLowerCase()}.waitForDeployment();
  console.log("${c} deployed to:", await ${c.toLowerCase()}.getAddress());`).join("\n\n")}

  console.log("\\n✓ All contracts deployed successfully.");
  console.log("Next: verify on Etherscan with 'npx hardhat verify'");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
`,
  };
}

