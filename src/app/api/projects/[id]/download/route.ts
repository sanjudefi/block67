function erc20Contracts(cfg: Record<string, string>, ver: string): GenFile[] {
  const name = cfg.tokenName || "MyToken";
  const sym  = cfg.symbol    || "MTK";
  const supply = cfg.totalSupply || "1000000000";
  const desc = cfg.description || "ERC-20 token";
  const mintable = cfg.mintable === "true";
  const burnable = cfg.burnable === "true";

  const burnable_import = burnable ? `\nimport "@openzeppelin/contracts/token/ERC20/extensions/ERC20Burnable.sol";` : "";
  const burnable_inherit = burnable ? ", ERC20Burnable" : "";
  const mint_fn = mintable ? `
    /// @notice Mint new tokens (owner only)
    function mint(address to, uint256 amount) external onlyOwner {
        _mint(to, amount);
    }` : "";
  const burn_fn = !burnable && mintable ? `
    /// @notice Burn tokens from caller
    function burn(uint256 amount) external {
        _burn(msg.sender, amount);
    }` : "";

  return [{
    path: "contracts/Token.sol",
    content: `// SPDX-License-Identifier: MIT
pragma solidity ^${ver};

import "@openzeppelin/contracts/token/ERC20/ERC20.sol";${burnable_import}
import "@openzeppelin/contracts/access/Ownable.sol";

/**
 * @title ${name}
 * @notice ${desc}
 * @dev Generated by block67.app
 */
contract ${name.replace(/\s+/g, "")} is ERC20${burnable_inherit}, Ownable {
    uint256 public constant INITIAL_SUPPLY = ${supply} * (10 ** 18);

    constructor(address initialOwner)
        ERC20("${name}", "${sym}")
        Ownable(initialOwner)
    {
        _mint(initialOwner, INITIAL_SUPPLY);
    }
${mint_fn}${burn_fn}
    /// @notice Recover ERC-20 tokens accidentally sent to this contract
    function recoverERC20(address token, uint256 amount) external onlyOwner {
        IERC20(token).transfer(owner(), amount);
    }
}
`,
  }];
}

